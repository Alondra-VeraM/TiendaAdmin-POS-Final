-- 1. CÓDIGOS PADRE (cajas / paquetes cerrados)
-- Ejemplo: la caja de leche tiene su propio código de barras y contiene 12 piezas.
-- También sirve para guardar el código que usa el proveedor en su factura.
CREATE TABLE IF NOT EXISTS public.product_packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode VARCHAR(60) NOT NULL UNIQUE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    units INTEGER NOT NULL DEFAULT 1 CHECK (units > 0),
    description VARCHAR(150),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_packages_product ON public.product_packages(product_id);

-- 2. FACTURAS CFDI YA RECIBIDAS (evita sumar dos veces la misma factura)
CREATE TABLE IF NOT EXISTS public.supplier_invoices (
    uuid VARCHAR(60) PRIMARY KEY,
    supplier_name VARCHAR(200),
    supplier_rfc VARCHAR(20),
    folio VARCHAR(60),
    total NUMERIC(12, 2),
    pieces_added INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.product_packages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.supplier_invoices ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'product_packages' AND policyname = 'Permitir todo product_packages') THEN
        CREATE POLICY "Permitir todo product_packages" ON public.product_packages FOR ALL USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'supplier_invoices' AND policyname = 'Permitir todo supplier_invoices') THEN
        CREATE POLICY "Permitir todo supplier_invoices" ON public.supplier_invoices FOR ALL USING (true);
    END IF;
END $$;

-- 3. FUNCIÓN DEL SERVIDOR: SUMAR MERCANCÍA AL STOCK
-- Recibe cualquier código (pieza o caja). Si es el código de una caja,
-- multiplica automáticamente por las piezas que contiene.
-- p_unit_cost es el costo de lo que se escaneó (si es caja, el costo de la caja).
CREATE OR REPLACE FUNCTION public.receive_stock(
    p_code TEXT,
    p_quantity INTEGER DEFAULT 1,
    p_unit_cost NUMERIC DEFAULT NULL,
    p_source TEXT DEFAULT 'Recepción'
)
RETURNS JSON
LANGUAGE plpgsql
AS $$
DECLARE
    v_code TEXT := trim(p_code);
    v_product public.products%ROWTYPE;
    v_product_id BIGINT;
    v_units INTEGER := 1;
    v_is_package BOOLEAN := false;
    v_added INTEGER;
    v_new_stock INTEGER;
    v_new_cost NUMERIC(12, 2);
BEGIN
    IF v_code IS NULL OR v_code = '' THEN
        RETURN json_build_object('ok', false, 'error', 'Código vacío');
    END IF;

    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RETURN json_build_object('ok', false, 'error', 'La cantidad debe ser mayor a 0');
    END IF;

    -- a) ¿Es el código de una pieza?
    SELECT id INTO v_product_id
    FROM public.products
    WHERE barcode = v_code OR sku = v_code
    LIMIT 1;

    -- b) Si no, ¿es el código de una caja (código padre)?
    IF v_product_id IS NULL THEN
        SELECT product_id, units INTO v_product_id, v_units
        FROM public.product_packages
        WHERE barcode = v_code;

        IF v_product_id IS NOT NULL THEN
            v_is_package := true;
        END IF;
    END IF;

    IF v_product_id IS NULL THEN
        RETURN json_build_object('ok', false, 'error', 'Código no registrado: ' || v_code);
    END IF;

    -- Bloquear la fila para que dos celulares no se pisen
    SELECT * INTO v_product FROM public.products WHERE id = v_product_id FOR UPDATE;

    v_added := p_quantity * v_units;
    v_new_stock := v_product.stock + v_added;
    v_new_cost := CASE
        WHEN p_unit_cost IS NOT NULL AND p_unit_cost > 0 THEN round(p_unit_cost / v_units, 2)
        ELSE v_product.cost
    END;

    UPDATE public.products
    SET stock = v_new_stock, cost = v_new_cost
    WHERE id = v_product.id;

    INSERT INTO public.inventory_movements (
        product_id, movement_type, quantity, previous_stock, new_stock, unit_cost, notes, created_by
    ) VALUES (
        v_product.id, 'purchase_entry', v_added, v_product.stock, v_new_stock, v_new_cost,
        CASE WHEN v_is_package
            THEN 'Entrada: ' || p_quantity || ' caja(s) de ' || v_units || ' pzas (código ' || v_code || ')'
            ELSE 'Entrada: ' || p_quantity || ' pza(s)'
        END,
        COALESCE(p_source, 'Recepción')
    );

    RETURN json_build_object(
        'ok', true,
        'product_id', v_product.id,
        'product_name', v_product.name,
        'is_package', v_is_package,
        'units_per_package', v_units,
        'units_added', v_added,
        'new_stock', v_new_stock,
        'unit_cost', v_new_cost
    );
END;
$$;

GRANT EXECUTE ON FUNCTION public.receive_stock(TEXT, INTEGER, NUMERIC, TEXT) TO anon, authenticated;

-- 4. TIEMPO REAL: avisar a todas las pantallas cuando cambie el stock
DO $$
BEGIN

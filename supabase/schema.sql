-- 1. ACTIVACIÓN DE EXTENSIONES NECESARIAS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- =============================================================================
-- 2. TABLA: CONFIGURACIÓN GENERAL DEL NEGOCIO (store_settings)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.store_settings (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    store_name VARCHAR(150) NOT NULL DEFAULT 'Abarrotes & Mini Super NEXUS',
    business_name VARCHAR(200) NOT NULL DEFAULT 'NEXUS Retail S.A. de C.V.',
    tax_id VARCHAR(50) DEFAULT 'XAXX010101000',
    phone VARCHAR(30) DEFAULT '55-1234-5678',
    email VARCHAR(120) DEFAULT 'contacto@nexusretail.local',
    address TEXT DEFAULT 'Av. Insurgentes Sur 1234, Col. Del Valle, Benito Juárez, CDMX',
    ticket_footer TEXT DEFAULT '¡Gracias por su compra! Conserve este ticket para cualquier cambio o aclaración.',
    currency_code VARCHAR(10) DEFAULT 'MXN',
    currency_symbol VARCHAR(5) DEFAULT '$',
    admin_pin VARCHAR(20) DEFAULT '1234',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())

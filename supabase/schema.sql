-- =============================================================================
-- 3. TABLA: TERMINALES / CAJAS REGISTRADORAS (terminals)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.terminals (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    code VARCHAR(20) NOT NULL UNIQUE, -- 'C1', 'C2'
    name VARCHAR(100) NOT NULL,       -- 'Caja 1', 'Caja 2'
    is_active BOOLEAN NOT NULL DEFAULT true,
    last_sync_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- =============================================================================
-- 4. TABLA: USUARIOS Y PERFILES (users)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    username VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('cajero', 'admin')),
    pin VARCHAR(20),                   -- PIN rápido numérico (ej. 1234 para admin)
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- =============================================================================
-- 5. TABLA: CATEGORÍAS DE PRODUCTOS (categories)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.categories (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- =============================================================================
-- 6. TABLA: CATÁLOGO DE PRODUCTOS (products)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode VARCHAR(60) NOT NULL UNIQUE,
    sku VARCHAR(60),
    name VARCHAR(200) NOT NULL,
    display_name VARCHAR(200),
    category VARCHAR(100) NOT NULL DEFAULT 'General',
    cost NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (cost >= 0),
    price NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (price >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    min_stock INTEGER NOT NULL DEFAULT 5,
    icon_type VARCHAR(40) DEFAULT 'bread', -- 'milk', 'egg', 'soda', 'bread', 'general'
    promo_rule JSONB,                      -- Reglas de descuento/combo ej: {"type":"bundle","quantity":3,"bundle_price":45.00}
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_products_barcode ON public.products(barcode);
CREATE INDEX IF NOT EXISTS idx_products_sku ON public.products(sku);
CREATE INDEX IF NOT EXISTS idx_products_name ON public.products(name);

-- =============================================================================
-- 7. TABLA: SERVICIOS RÁPIDOS Y RECARGAS (quick_services)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.quick_services (
    id VARCHAR(50) PRIMARY KEY, -- 'recargas', 'pago_1', etc.
    name VARCHAR(120) NOT NULL,
    icon VARCHAR(40) DEFAULT 'phone',
    subtitle VARCHAR(120),
    commission NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- =============================================================================
-- 8. TABLA: VENTAS / TICKETS (sales)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio VARCHAR(40) NOT NULL UNIQUE, -- '#44939', '#TK-2024-0842'
    terminal_code VARCHAR(20) DEFAULT 'C1',
    terminal_name VARCHAR(50) DEFAULT 'Caja 1',
    cashier_name VARCHAR(100) DEFAULT 'Elena R.',
    total_items INTEGER NOT NULL DEFAULT 1 CHECK (total_items >= 0),
    total_pieces INTEGER NOT NULL DEFAULT 1 CHECK (total_pieces >= 0),
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    discount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    total_net NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    payment_method VARCHAR(30) NOT NULL DEFAULT 'cash' CHECK (payment_method IN ('cash', 'card', 'qr', 'codi', 'mixed')),
    cash_received NUMERIC(12, 2),
    cash_change NUMERIC(12, 2),
    status VARCHAR(20) NOT NULL DEFAULT 'completed' CHECK (status IN ('completed', 'cancelled')),
    cancelled_at TIMESTAMPTZ,
    cancellation_reason TEXT,
    cancelled_by VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_sales_folio ON public.sales(folio);
CREATE INDEX IF NOT EXISTS idx_sales_created_at ON public.sales(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sales_status ON public.sales(status);

-- =============================================================================
-- 9. TABLA: DETALLE DE ARTÍCULOS POR VENTA (sale_items)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES public.sales(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    barcode VARCHAR(60),
    sku VARCHAR(60),
    product_name VARCHAR(200) NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    discount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    subtotal NUMERIC(12, 2) NOT NULL,
    promo_applied VARCHAR(150),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_sale_items_sale_id ON public.sale_items(sale_id);

-- =============================================================================
-- 10. TABLA: KARDEX DE MOVIMIENTOS DE INVENTARIO (inventory_movements)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    movement_type VARCHAR(40) NOT NULL CHECK (
        movement_type IN (
            'sale',                 -- Salida por venta regular
            'sale_cancellation',    -- Reingreso por venta cancelada
            'purchase_entry',       -- Entrada por compra a proveedor
            'shrinkage_damaged',    -- Merma por producto dañado
            'shrinkage_expired',    -- Merma por producto caducado
            'shrinkage_theft',      -- Merma por faltante / robo
            'manual_adjustment'     -- Ajuste manual de inventario
        )
    ),
    quantity INTEGER NOT NULL,      -- Positivo si entra, Negativo si sale
    previous_stock INTEGER NOT NULL,
    new_stock INTEGER NOT NULL,
    unit_cost NUMERIC(12, 2),
    notes TEXT,
    created_by VARCHAR(100) DEFAULT 'Sistema',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_movements_product ON public.inventory_movements(product_id);
CREATE INDEX IF NOT EXISTS idx_movements_type ON public.inventory_movements(movement_type);

-- =============================================================================
-- 11. TABLA: CORTES DE CAJA Y TURNOS (cash_cuts)
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.cash_cuts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_code VARCHAR(20) NOT NULL DEFAULT 'C1',
    terminal_name VARCHAR(50) NOT NULL DEFAULT 'Caja 1',
    cashier_name VARCHAR(100) NOT NULL DEFAULT 'Elena R.',
    opened_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    closed_at TIMESTAMPTZ,
    initial_fund NUMERIC(12, 2) NOT NULL DEFAULT 1000.00,
    total_sales_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    total_sales_count INTEGER NOT NULL DEFAULT 0,
    cash_sales NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    card_sales NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    qr_sales NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    codi_sales NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    cash_inflows NUMERIC(12, 2) NOT NULL DEFAULT 0.00,     -- Entradas extraordinarias (+)
    cash_outflows NUMERIC(12, 2) NOT NULL DEFAULT 0.00,    -- Salidas extraordinarias (-)
    supplier_payouts NUMERIC(12, 2) NOT NULL DEFAULT 0.00, -- Pago a proveedores (-)
    expected_cash NUMERIC(12, 2) NOT NULL DEFAULT 0.00,    -- Fondo + Efectivo + Entradas - Salidas - Prov
    counted_cash NUMERIC(12, 2) NOT NULL DEFAULT 0.00,     -- Efectivo físico contado por el cajero
    difference NUMERIC(12, 2) NOT NULL DEFAULT 0.00,       -- Contado - Esperado (Sobrante / Faltante)
    status VARCHAR(20) NOT NULL DEFAULT 'closed' CHECK (status IN ('open', 'closed')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);


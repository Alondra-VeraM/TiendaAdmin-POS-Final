-- A) Trigger para actualizar el campo updated_at
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_products_updated_at ON public.products;
CREATE TRIGGER trg_products_updated_at
BEFORE UPDATE ON public.products
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

-- B) Trigger para descontar stock automáticamente al registrar artículos vendidos
CREATE OR REPLACE FUNCTION public.handle_sale_item_stock()
RETURNS TRIGGER AS $$
DECLARE
    curr_stock INTEGER;
    new_stk INTEGER;
BEGIN
    IF NEW.product_id IS NOT NULL THEN
        SELECT stock INTO curr_stock FROM public.products WHERE id = NEW.product_id;
        IF curr_stock IS NOT NULL THEN
            new_stk := GREATEST(0, curr_stock - NEW.quantity);
            
            -- Actualizar producto
            UPDATE public.products 
            SET stock = new_stk 
            WHERE id = NEW.product_id;

            -- Registrar movimiento en Kardex
            INSERT INTO public.inventory_movements (
                product_id,
                movement_type,
                quantity,
                previous_stock,
                new_stock,
                notes,
                created_by
            ) VALUES (
                NEW.product_id,
                'sale',
                -NEW.quantity,
                curr_stock,
                new_stk,
                'Salida por venta folio ticket',
                'Punto de Venta'
            );
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_deduct_stock_on_sale_item ON public.sale_items;
CREATE TRIGGER trg_deduct_stock_on_sale_item
AFTER INSERT ON public.sale_items
FOR EACH ROW EXECUTE FUNCTION public.handle_sale_item_stock();

-- C) Trigger para restaurar stock cuando una venta se cancela
CREATE OR REPLACE FUNCTION public.handle_sale_cancellation_restore()
RETURNS TRIGGER AS $$
DECLARE
    item RECORD;
    curr_stock INTEGER;
BEGIN
    IF OLD.status = 'completed' AND NEW.status = 'cancelled' THEN
        FOR item IN SELECT product_id, quantity FROM public.sale_items WHERE sale_id = NEW.id LOOP
            IF item.product_id IS NOT NULL THEN
                SELECT stock INTO curr_stock FROM public.products WHERE id = item.product_id;
                IF curr_stock IS NOT NULL THEN
                    UPDATE public.products 
                    SET stock = curr_stock + item.quantity 
                    WHERE id = item.product_id;

                    INSERT INTO public.inventory_movements (
                        product_id,
                        movement_type,
                        quantity,
                        previous_stock,
                        new_stock,
                        notes,
                        created_by
                    ) VALUES (
                        item.product_id,
                        'sale_cancellation',
                        item.quantity,
                        curr_stock,
                        curr_stock + item.quantity,
                        'Reingreso por cancelación de venta folio ' || NEW.folio,
                        COALESCE(NEW.cancelled_by, 'Administrador')
                    );
                END IF;
            END IF;
        END LOOP;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_restore_stock_on_cancel ON public.sales;
CREATE TRIGGER trg_restore_stock_on_cancel
AFTER UPDATE ON public.sales
FOR EACH ROW EXECUTE FUNCTION public.handle_sale_cancellation_restore();

